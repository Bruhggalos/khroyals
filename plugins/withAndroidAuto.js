/**
 * Android Auto: group messages are read aloud on the car screen, and the
 * driver can answer by voice.
 *
 * Android Auto only shows notifications from messaging apps that use
 * MessagingStyle with a Reply action (and a Mark-as-read action) that work
 * without opening the phone. expo-notifications can't build those, so this
 * plugin adds a little native code to the Android app:
 *
 *   CarMessagingService  replaces expo-notifications' Firebase service. Group
 *                        post pushes (they carry a replyToken) become
 *                        conversation notifications; everything else is
 *                        handed to expo-notifications unchanged.
 *   CarMessaging         builds the notification (keeps the last few messages
 *                        per group, so the car reads the thread).
 *   CarReplyReceiver     sends a reply through the reply_from_push database
 *                        function (no sign-in needed: the token only allows
 *                        replying in that group, for 24 hours) and marks
 *                        conversations read.
 *
 * Plus the manifest entry Android Auto looks for (automotive_app_desc.xml).
 * android/ is generated by prebuild; never edit those files by hand.
 */
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withAppBuildGradle, withDangerousMod } = require('expo/config-plugins');

const EXPO_SERVICE = 'expo.modules.notifications.service.ExpoFirebaseMessagingService';
const MESSAGING_EVENT = 'com.google.firebase.MESSAGING_EVENT';
const CAR_META = 'com.google.android.gms.car.application';
const DEPENDENCIES = [
  "implementation 'com.google.firebase:firebase-messaging:25.0.1'",
  "implementation 'androidx.core:core:1.17.0'",
];

const AUTOMOTIVE_XML = `<?xml version="1.0" encoding="utf-8"?>
<automotiveApp>
  <uses name="notification" />
</automotiveApp>
`;

/** Register the car notification service/receiver and the Android Auto descriptor in the manifest. */
function addCarManifestEntries(manifest, pkg) {
  manifest.manifest.$['xmlns:tools'] ??= 'http://schemas.android.com/tools';
  const app = manifest.manifest.application[0];
  app['meta-data'] = (app['meta-data'] ?? []).filter((m) => m.$['android:name'] !== CAR_META);
  app['meta-data'].push({ $: { 'android:name': CAR_META, 'android:resource': '@xml/automotive_app_desc' } });

  const ours = [`${pkg}.auto.CarMessagingService`, EXPO_SERVICE];
  app.service = (app.service ?? []).filter((s) => !ours.includes(s.$['android:name']));
  // Only one service may receive Firebase messages: ours (it forwards the rest to Expo's).
  app.service.push({ $: { 'android:name': EXPO_SERVICE, 'tools:node': 'remove' } });
  app.service.push({
    $: { 'android:name': `${pkg}.auto.CarMessagingService`, 'android:exported': 'false' },
    'intent-filter': [{ action: [{ $: { 'android:name': MESSAGING_EVENT } }] }],
  });

  app.receiver = (app.receiver ?? []).filter((r) => r.$['android:name'] !== `${pkg}.auto.CarReplyReceiver`);
  app.receiver.push({ $: { 'android:name': `${pkg}.auto.CarReplyReceiver`, 'android:exported': 'false' } });
  return manifest;
}

/** Make sure app/build.gradle can compile the Firebase service subclass and NotificationCompat. */
function addDependencies(gradle) {
  const missing = DEPENDENCIES.filter((d) => !gradle.includes(d));
  if (!missing.length) return gradle;
  return gradle.replace(/dependencies\s*\{/, (m) => `${m}\n    // Android Auto messaging (plugins/withAndroidAuto.js)\n    ${missing.join('\n    ')}`);
}

const kt = (s) => JSON.stringify(s);   // a Kotlin string literal

/** The Kotlin sources, keyed by file name. */
function kotlinSources(pkg, supabaseUrl, supabaseKey) {
  const p = `${pkg}.auto`;
  return {
    'CarMessagingService.kt': `package ${p}

import com.google.firebase.messaging.RemoteMessage
import expo.modules.notifications.service.ExpoFirebaseMessagingService
import org.json.JSONObject

/** Group post pushes become car-ready conversations; everything else goes to expo-notifications. */
class CarMessagingService : ExpoFirebaseMessagingService() {
  override fun onMessageReceived(remoteMessage: RemoteMessage) {
    val data = try { JSONObject(remoteMessage.data["body"] ?: "") } catch (e: Exception) { null }
    val token = data?.optString("replyToken").orEmpty()
    val groupId = data?.optString("groupId").orEmpty()
    if (data == null || token.isEmpty() || groupId.isEmpty()) {
      super.onMessageReceived(remoteMessage)
      return
    }
    try {
      CarMessaging.showMessage(
        this,
        groupId = groupId,
        groupName = data.optString("groupName").ifEmpty { remoteMessage.data["title"].orEmpty() },
        sender = data.optString("sender").ifEmpty { "Someone" },
        text = data.optString("text").ifEmpty { remoteMessage.data["message"].orEmpty() },
        token = token,
      )
    } catch (e: Exception) {
      super.onMessageReceived(remoteMessage)   // never lose a notification
    }
  }
}
`,
    'CarMessaging.kt': `package ${p}

import android.annotation.SuppressLint
import android.app.NotificationChannel
import android.app.NotificationManager
import android.app.PendingIntent
import android.content.Context
import android.content.Intent
import android.net.Uri
import android.os.Build
import androidx.core.app.NotificationCompat
import androidx.core.app.NotificationManagerCompat
import androidx.core.app.Person
import androidx.core.app.RemoteInput

/** Conversation notifications that Android Auto can read aloud and reply to. */
object CarMessaging {
  const val SUPABASE_URL = ${kt(supabaseUrl)}
  const val SUPABASE_KEY = ${kt(supabaseKey)}
  const val CHANNEL = "default"
  const val ACTION_REPLY = "${p}.REPLY"
  const val ACTION_READ = "${p}.READ"
  const val KEY_TEXT = "reply_text"
  const val EXTRA_GROUP = "groupId"
  const val EXTRA_NAME = "groupName"
  const val EXTRA_TOKEN = "replyToken"
  private const val KEEP = 8

  private val me = Person.Builder().setName("You").setKey("me").build()

  fun notificationId(groupId: String) = groupId.hashCode()

  fun showMessage(ctx: Context, groupId: String, groupName: String, sender: String, text: String, token: String) {
    val style = currentStyle(ctx, groupId, groupName)
    style.addMessage(NotificationCompat.MessagingStyle.Message(text, System.currentTimeMillis(),
      Person.Builder().setName(sender).setKey(sender).build()))
    post(ctx, groupId, groupName, token, style, alert = true)
  }

  /** After the driver replies: show their message in the thread (or why it failed), quietly. */
  fun showReply(ctx: Context, groupId: String, groupName: String, token: String, text: String, error: String?) {
    val style = currentStyle(ctx, groupId, groupName)
    if (error == null) {
      style.addMessage(NotificationCompat.MessagingStyle.Message(text, System.currentTimeMillis(), null as Person?))
    } else {
      style.addMessage(NotificationCompat.MessagingStyle.Message("Couldn't send: $error", System.currentTimeMillis(),
        Person.Builder().setName("KH Royals").setKey("app").build()))
    }
    post(ctx, groupId, groupName, token, style, alert = error != null)
  }

  fun markRead(ctx: Context, groupId: String) {
    NotificationManagerCompat.from(ctx).cancel(notificationId(groupId))
  }

  /** The conversation already on screen for this group (so the car reads the thread), or a new one. */
  private fun currentStyle(ctx: Context, groupId: String, groupName: String): NotificationCompat.MessagingStyle {
    val style = NotificationCompat.MessagingStyle(me).setConversationTitle(groupName).setGroupConversation(true)
    val nm = ctx.getSystemService(Context.NOTIFICATION_SERVICE) as NotificationManager
    val active = nm.activeNotifications.firstOrNull { it.id == notificationId(groupId) }?.notification
    val old = active?.let { NotificationCompat.MessagingStyle.extractMessagingStyleFromNotification(it) }
    old?.messages?.takeLast(KEEP - 1)?.forEach { style.addMessage(it) }
    return style
  }

  @SuppressLint("MissingPermission")   // notify() is wrapped: no permission just means no notification
  private fun post(ctx: Context, groupId: String, groupName: String, token: String,
                   style: NotificationCompat.MessagingStyle, alert: Boolean) {
    ensureChannel(ctx)
    val id = notificationId(groupId)
    val flagsMutable = PendingIntent.FLAG_UPDATE_CURRENT or
      (if (Build.VERSION.SDK_INT >= 31) PendingIntent.FLAG_MUTABLE else 0)
    val flagsImmutable = PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE

    fun broadcast(action: String) = Intent(ctx, CarReplyReceiver::class.java).setAction(action)
      .putExtra(EXTRA_GROUP, groupId).putExtra(EXTRA_NAME, groupName).putExtra(EXTRA_TOKEN, token)

    val reply = NotificationCompat.Action.Builder(android.R.drawable.ic_menu_send, "Reply",
        PendingIntent.getBroadcast(ctx, id, broadcast(ACTION_REPLY), flagsMutable))
      .addRemoteInput(RemoteInput.Builder(KEY_TEXT).setLabel("Reply").build())
      .setAllowGeneratedReplies(true)
      .setSemanticAction(NotificationCompat.Action.SEMANTIC_ACTION_REPLY)
      .setShowsUserInterface(false)
      .build()
    val read = NotificationCompat.Action.Builder(android.R.drawable.ic_menu_view, "Mark as read",
        PendingIntent.getBroadcast(ctx, id + 1, broadcast(ACTION_READ), flagsImmutable))
      .setSemanticAction(NotificationCompat.Action.SEMANTIC_ACTION_MARK_AS_READ)
      .setShowsUserInterface(false)
      .build()
    val open = PendingIntent.getActivity(ctx, id + 2,
      Intent(Intent.ACTION_VIEW, Uri.parse("khroyals://group/$groupId")).setPackage(ctx.packageName)
        .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK), flagsImmutable)

    val n = NotificationCompat.Builder(ctx, CHANNEL)
      .setSmallIcon(smallIcon(ctx))
      .setStyle(style)
      .setCategory(NotificationCompat.CATEGORY_MESSAGE)
      .setPriority(NotificationCompat.PRIORITY_HIGH)
      .setContentIntent(open)
      .addAction(reply)
      .addInvisibleAction(read)
      .setAutoCancel(true)
      .setOnlyAlertOnce(!alert)
      .build()
    try {
      NotificationManagerCompat.from(ctx).notify(id, n)
    } catch (e: SecurityException) {
      // Notifications are turned off for the app.
    }
  }

  private fun smallIcon(ctx: Context): Int {
    val res = ctx.resources.getIdentifier("notification_icon", "drawable", ctx.packageName)
    return if (res != 0) res else ctx.applicationInfo.icon
  }

  private fun ensureChannel(ctx: Context) {
    if (Build.VERSION.SDK_INT < 26) return
    val nm = ctx.getSystemService(Context.NOTIFICATION_SERVICE) as NotificationManager
    if (nm.getNotificationChannel(CHANNEL) == null) {
      nm.createNotificationChannel(NotificationChannel(CHANNEL, "Royals Connect", NotificationManager.IMPORTANCE_HIGH))
    }
  }
}
`,
    'CarReplyReceiver.kt': `package ${p}

import android.content.BroadcastReceiver
import android.content.Context
import android.content.Intent
import androidx.core.app.RemoteInput
import org.json.JSONObject
import java.net.HttpURLConnection
import java.net.URL
import kotlin.concurrent.thread

/** Reply and Mark-as-read from the notification or Android Auto, without opening the app. */
class CarReplyReceiver : BroadcastReceiver() {
  override fun onReceive(ctx: Context, intent: Intent) {
    val groupId = intent.getStringExtra(CarMessaging.EXTRA_GROUP) ?: return
    val groupName = intent.getStringExtra(CarMessaging.EXTRA_NAME).orEmpty()
    val token = intent.getStringExtra(CarMessaging.EXTRA_TOKEN).orEmpty()
    when (intent.action) {
      CarMessaging.ACTION_READ -> CarMessaging.markRead(ctx, groupId)
      CarMessaging.ACTION_REPLY -> {
        val text = RemoteInput.getResultsFromIntent(intent)?.getCharSequence(CarMessaging.KEY_TEXT)?.toString()?.trim()
        if (text.isNullOrEmpty()) return
        val pending = goAsync()
        thread {
          try {
            val error = send(token, text)
            CarMessaging.showReply(ctx.applicationContext, groupId, groupName, token, text, error)
          } finally {
            pending.finish()
          }
        }
      }
    }
  }

  /** Post the reply; returns null when it worked, or a short reason. */
  private fun send(token: String, text: String): String? = try {
    val conn = URL("\${CarMessaging.SUPABASE_URL}/rest/v1/rpc/reply_from_push").openConnection() as HttpURLConnection
    conn.requestMethod = "POST"
    conn.connectTimeout = 15000
    conn.readTimeout = 15000
    conn.doOutput = true
    conn.setRequestProperty("apikey", CarMessaging.SUPABASE_KEY)
    conn.setRequestProperty("Content-Type", "application/json")
    conn.outputStream.use { it.write(JSONObject().put("p_token", token).put("p_text", text).toString().toByteArray()) }
    val code = conn.responseCode
    if (code in 200..299) {
      null
    } else {
      val body = (conn.errorStream ?: conn.inputStream)?.bufferedReader()?.use { it.readText() }.orEmpty()
      try { JSONObject(body).optString("message").ifEmpty { "error $code" } } catch (e: Exception) { "error $code" }
    }
  } catch (e: Exception) {
    "no connection"
  }
}
`,
  };
}

const withAndroidAuto = (config) => {
  const pkg = config.android?.package;
  if (!pkg) throw new Error('withAndroidAuto: set expo.android.package');
  const { supabaseUrl = '', supabaseKey = '' } = config.extra ?? {};

  config = withAndroidManifest(config, (c) => { c.modResults = addCarManifestEntries(c.modResults, pkg); return c; });
  config = withAppBuildGradle(config, (c) => { c.modResults.contents = addDependencies(c.modResults.contents); return c; });
  config = withDangerousMod(config, ['android', (c) => {
    const main = path.join(c.modRequest.platformProjectRoot, 'app/src/main');
    fs.mkdirSync(path.join(main, 'res/xml'), { recursive: true });
    fs.writeFileSync(path.join(main, 'res/xml/automotive_app_desc.xml'), AUTOMOTIVE_XML);
    const dir = path.join(main, 'java', ...pkg.split('.'), 'auto');
    fs.mkdirSync(dir, { recursive: true });
    for (const [name, src] of Object.entries(kotlinSources(pkg, supabaseUrl, supabaseKey))) fs.writeFileSync(path.join(dir, name), src);
    return c;
  }]);
  return config;
};

module.exports = withAndroidAuto;
module.exports.addCarManifestEntries = addCarManifestEntries;
module.exports.addDependencies = addDependencies;
module.exports.kotlinSources = kotlinSources;
