#!/usr/bin/env python3
"""
Build supabase/seed.sql from the Royals Connect demo data (mock-db/comms) and
the real 2026-27 school calendar (content/site/calendar.json).

    python3 scripts/gen_seed.py

The seed expects the demo accounts to exist already (scripts/seed_supabase.mjs
creates them through the Auth admin API with the same ids). Every demo id like
"u-admin" maps to a stable uuid: md5('khroyals:' || id)::uuid.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
load = lambda name, key: json.load(open(os.path.join(ROOT, 'mock-db/comms', f'{name}.json')))[key]
users, groups, memberships = load('users', 'users'), load('groups', 'groups'), load('memberships', 'memberships')
posts, comments, roster = load('posts', 'posts'), load('comments', 'comments'), load('roster', 'roster')
calendar = json.load(open(os.path.join(ROOT, 'content/site/calendar.json')))

out = []
w = out.append


def q(v):
    """SQL literal."""
    if v is None:
        return 'null'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, (dict, list)):
        return q(json.dumps(v, ensure_ascii=False)) + '::jsonb'
    return "'" + str(v).replace("'", "''") + "'"


def sid(legacy):
    return 'null' if legacy is None else f"app.seed_id({q(legacy)})"


def arr(values, typ='text'):
    return 'null' if not values else f"array[{', '.join(q(v) for v in values)}]::{typ}[]"


w('-- Generated by scripts/gen_seed.py — demo data for Royals Connect + the 2026–27 school calendar.')
w('begin;')
w("create or replace function app.seed_id(legacy text) returns uuid language sql immutable as $$ select md5('khroyals:' || legacy)::uuid $$;")

w('\n-- People (accounts are created first by scripts/seed_supabase.mjs)')
for u in users:
    w(f"update public.profiles set first_name = {q(u['firstName'])}, last_name = {q(u['lastName'])}, "
      f"school_role = {q('staff' if u['schoolRole'] == 'admin' else u['schoolRole'])}, grade = {q(u.get('grade'))}, avatar_url = {q(u.get('avatar'))} "
      f"where id = {sid(u['id'])};")

w('\n-- Rosters')
for kind, key, lead in (('section', 'sections', 'teacherId'), ('team', 'teams', 'coachId'), ('club', 'clubs', 'sponsorId')):
    for r in roster[key]:
        w(f"insert into public.rosters values ({q(r['id'])}, {q(kind)}, {q(r['name'])}, {sid(r.get(lead))}) on conflict (id) do nothing;")
rm = sorted({(rid, u['id']) for u in users for k in ('sectionIds', 'teamIds', 'clubIds') for rid in u.get(k, [])})
for rid, uid in rm:
    w(f"insert into public.roster_members values ({q(rid)}, {sid(uid)}) on conflict do nothing;")
for u in users:
    for s in u.get('guardianOf', []):
        w(f"insert into public.guardians values ({sid(u['id'])}, {sid(s)}) on conflict do nothing;")

w('\n-- Groups')
for g in groups:
    w(f"insert into public.groups (id, slug, name, description, icon, color, category, tags, settings, created_by, created_at) values "
      f"({sid(g['id'])}, {q(g['id'])}, {q(g['name'])}, {q(g['description'])}, {q(g['icon'])}, {q(g['color'])}, {q(g['category'])}, "
      f"{arr(g.get('tags')) if g.get('tags') else ''''{}''' }, {q(g['settings'])}, {sid(g['createdBy'])}, {q(g['createdAt'])}) on conflict (id) do nothing;")
for g in groups:
    if g.get('parentGroupId'):
        w(f"update public.groups set parent_group_id = {sid(g['parentGroupId'])} where id = {sid(g['id'])};")
for g in groups:
    for r in g['assignmentRules']:
        rosters = r.get('sectionIds', []) + r.get('teamIds', []) + r.get('clubIds', [])
        w(f"insert into public.assignment_rules values ({sid(g['id'] + ':' + r['id'])}, {sid(g['id'])}, {arr(r.get('schoolRoles'))}, "
          f"{arr(r.get('grades'), 'int')}, {arr(rosters)}, {q(r.get('includeGuardiansAs'))}, {q(r['assignAs'])}) on conflict (id) do nothing;")

w('\n-- Manual memberships (rule memberships are created by the sync triggers)')
for m in memberships:
    if m['source'] == 'rule':
        continue
    w(f"insert into public.memberships (group_id, user_id, role, source, notification, joined_at) values "
      f"({sid(m['groupId'])}, {sid(m['userId'])}, {q(m['role'])}, {q(m['source'])}, {q(m.get('notification'))}, {q(m['joinedAt'])}) "
      f"on conflict (group_id, user_id) do update set role = excluded.role, source = excluded.source;")
for m in memberships:
    if m.get('mutedUntil') or m.get('canPost') is False:
        w(f"update public.memberships set muted_until = {q(m.get('mutedUntil'))}, can_post = {q(m.get('canPost', True))} "
          f"where group_id = {sid(m['groupId'])} and user_id = {sid(m['userId'])};")

# No demo account gets admin powers: the demo password ships in the public app.
# The real director is named with scripts/supabase_setup.mjs --director=email.

w('\n-- Posts, polls, reactions, replies (demo history shouldn\'t trigger push notifications)')
w('alter table public.posts disable trigger notify_post;')
for p in posts:
    w(f"insert into public.posts (id, group_id, author_id, kind, title, body, attachments, status, pinned, comments_locked, score, created_at) values "
      f"({sid(p['id'])}, {sid(p['groupId'])}, {sid(p['authorId'])}, {q(p['kind'])}, {q(p.get('title'))}, {q(p['body'])}, {q(p['attachments'])}, "
      f"{q(p['status'])}, {q(p['pinned'])}, {q(p['commentsLocked'])}, {q(p['score'])}, {q(p['createdAt'])}) on conflict (id) do nothing;")
    for i, o in enumerate((p.get('poll') or {}).get('options', [])):
        oid = sid(p['id'] + ':' + o['id'])
        w(f"insert into public.poll_options values ({oid}, {sid(p['id'])}, {q(o['label'])}, {i + 1}) on conflict (id) do nothing;")
        for v in o['votes']:
            w(f"insert into public.poll_votes values ({oid}, {sid(p['id'])}, {sid(v)}) on conflict do nothing;")
    for emoji, ids in p['reactions'].items():
        for v in ids:
            w(f"insert into public.reactions values ({sid(p['id'])}, {sid(v)}, {q(emoji)}) on conflict do nothing;")
for c in comments:
    w(f"insert into public.comments (id, post_id, parent_comment_id, author_id, body, status, is_answer, score, created_at) values "
      f"({sid(c['id'])}, {sid(c['postId'])}, {sid(c['parentCommentId'])}, {sid(c['authorId'])}, {q(c['body'])}, {q(c['status'])}, "
      f"{q(c['isAnswer'])}, {q(c['score'])}, {q(c['createdAt'])}) on conflict (id) do nothing;")

w('alter table public.posts enable trigger notify_post;')

w('\n-- School calendar 2026–27 (from the official PDF via content/site/calendar.json)')
for e in calendar['events']:
    w(f"insert into public.events (id, title, starts_on, ends_on, all_day, category) values "
      f"({sid('cal:' + e['id'])}, {q(e['title'])}, {q(e['date'])}, {q(e['endDate'])}, true, {q(e['category'])}) on conflict (id) do nothing;")

w('\n-- Demo group events')
for key, gid, title, day, start, end, loc in (
    ('ev-vb-1', 'g-vb', 'Volleyball practice', '2026-10-20', '15:30', '17:30', 'Main gym'),
    ('ev-vb-2', 'g-vb', 'Away game – bus leaves 4:15', '2026-10-24', '16:15', '20:00', None),
    ('ev-eng-1', 'g-eng-p3', 'Essay draft due', '2026-10-23', None, None, None),
    ('ev-robo-1', 'g-robotics', 'Build night', '2026-10-22', '18:00', '20:00', 'STEM lab'),
):
    w(f"insert into public.events (id, group_id, title, starts_on, start_time, end_time, all_day, location, category) values "
      f"({sid(key)}, {sid(gid)}, {q(title)}, {q(day)}, {q(start)}, {q(end)}, {q(start is None)}, {q(loc)}, 'Group') on conflict (id) do nothing;")

w('commit;')
path = os.path.join(ROOT, 'supabase/seed.sql')
open(path, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(f'wrote {path}: {len(users)} people, {len(groups)} groups, {len(posts)} posts, {len(calendar["events"])} calendar dates')

# One file to paste into the dashboard's SQL editor: every migration, then the seed.
mig_dir = os.path.join(ROOT, 'supabase/migrations')
parts = ['-- Generated by scripts/gen_seed.py: all migrations + demo seed, for pasting into the Supabase SQL editor.',
         '-- (scripts/supabase_setup.mjs does the same through the Management API.)',
         'create schema if not exists app;',
         'create table if not exists app.applied_migrations (name text primary key, at timestamptz default now());']
for f in sorted(os.listdir(mig_dir)):
    if f.endswith('.sql'):
        parts += [f'\n-- ===== {f} =====', open(os.path.join(mig_dir, f), encoding='utf-8').read(),
                  f"insert into app.applied_migrations (name) values ('{f}') on conflict do nothing;"]
parts += ['\n-- ===== seed =====', '\n'.join(out)]
open(os.path.join(ROOT, 'supabase/setup_all.sql'), 'w', encoding='utf-8').write('\n'.join(parts) + '\n')
print('wrote supabase/setup_all.sql')
